"""The agent's eyes: tools that show it what it has made (a finished film, one scene's clip or a take of it, the photos of a
character or a place), and the tool that corrects a photo that is wrong. Pictures reach the model only when the owner allowed
sending pictures to the cloud, and never those of a character or a place whose photos are not all proven to be generated by
Contsy (agent_eyes.only_generated). Without the permission each tool still answers with the facts (what the scene should show,
what is said), so the agent knows what it could not check and says so. A conversation holds a limited number of pictures
(agent_host.MAX_PICTURES): when that is used up the tools answer with facts only.

Numbers: a scene argument counts from 0 (the first scene is 0) in every tool; the labels on the sheets say "Scene 1" for the
first scene, as the owner reads them, and the facts give both."""
from __future__ import annotations

from pathlib import Path

from . import agent_delivery as delivery, agent_eyes as eyes, characters, ffmpeg_utils, items, timeline
from . import overlays as text_overlays
from .agent_host import MAX_PICTURES, Host, ToolError
from .agent_tools import Reply, choice, number, obj, text, tool, whole
from .agent_tools_film import _ID, _load

NOT_ALLOWED = ("not shown: the owner has not allowed sending pictures to the cloud, so you cannot judge this by eye. Say in "
               "the report that it was not looked at.")
UPLOADED = ("not shown: it is not proven that everything in it was generated by Contsy (an uploaded or an edited photo, or "
            "an unreadable record), so its pictures stay on this PC. Say in the report that it was not looked at.")
FULL = (f"not shown: this conversation already holds {MAX_PICTURES} pictures, the most one request may carry. Rely on what "
        "you saw earlier and say in the report what you could not look at again.")
TRIES_PER_PHOTO = 2


def _answer(host: Host, facts: dict, make, scenes=()) -> object:
    """`facts`, with the pictures `make()` builds when they may be sent (a list of JPEG bytes)."""
    if not host.settings["send_images"]:
        return {**facts, "pictures": NOT_ALLOWED}
    if not host.room_for_pictures(1):
        return {**facts, "pictures": FULL}
    images = [one for one in make() if one]
    if not images:
        return {**facts, "pictures": "none could be made (the file could not be read)"}
    if not host.room_for_pictures(len(images)):
        return {**facts, "pictures": FULL}
    host.showed(len(images), scenes)
    return Reply(facts, images)


def _scene_facts(project: timeline.Project, index: int) -> dict:
    scene = project.scenes[index]
    return {"scene": index, "number": index + 1, "seconds": scene.seconds, "should_show": scene.prompt[:300],
            "lines": [cue.text for cue in scene.lines]}


@tool("look_at_film",
      "Look at the finished film as an editor would: frames of the scenes on labelled sheets (one to three frames per scene; at "
      "most 27 frames a call, so for a long film go on with from_scene), or one full-size frame at a moment you choose (to read "
      "a text or check a detail). Compare what you see with the brief and with each scene's description. Needs the film to be "
      "exported. You cannot hear it: the facts give what is said. The sheets say Scene 1 for the first scene; scene numbers in "
      "arguments start at 0.",
      obj({"project_id": text("The project id.", max_length=32, pattern=_ID),
           "per_scene": whole("Frames per scene on the sheets (default 1).", 1, 3),
           "from_scene": whole("The first scene to show (0 is the first; default 0).", 0, 59),
           "at_seconds": number("Show only one full-size frame at this second of the film.", 0, 3600)},
          ("project_id",)))
def _look_at_film(host: Host, args: dict):
    project = _load(args["project_id"])
    movie = delivery.export_of(project)
    if movie is None:
        raise ToolError("INVALID", "This project has no finished film yet. Export it first (timeline_job export), or look at "
                        "a scene's clip with look_at_scene.")
    length = round(ffmpeg_utils.probe_duration(movie) or 0.0, 1)
    facts = {"film": movie.name, "seconds": length}
    if project.overlays:  # the exact text Contsy burned in itself: what the frames should show besides the scenes
        facts["text_burned_in"] = text_overlays.view(project.overlays, length)
    facts["scenes"] = [_scene_facts(project, number) for number in range(len(project.scenes))]
    if host.settings["send_images"] and eyes.film_shows_uploaded(project):
        return {**facts, "pictures": UPLOADED}
    work = host.store.path("work")
    if "at_seconds" in args:
        shown = {}

        def one():
            data, moment = eyes.single_frame(movie, args["at_seconds"], work)
            shown["at"] = moment
            return [data]

        answer = _answer(host, facts, one)
        (answer.data if isinstance(answer, Reply) else answer)["shown_at_seconds"] = round(
            shown.get("at", args["at_seconds"]), 1)  # a time past the end shows the last frame
        return answer
    first, per_scene = args.get("from_scene", 0), args.get("per_scene", 1)
    covered: list[int] = []
    text_dropped: list[bool] = []

    def sheets():
        made, scenes = eyes.film_sheets(movie, project.scenes, per_scene, work, first=first)
        covered.extend(scenes)
        if project.overlays and first == 0:  # a frame in the middle of every text laid over the film
            shown = [(f"Text {number}", (span[0] + span[1]) / 2) for number, overlay in enumerate(project.overlays, 1)
                     if (span := text_overlays.window(overlay, length))]
            if shown and not host.room_for_pictures(len(made) + 1):  # drop the text sheet alone, not the scenes with it
                text_dropped.append(True)
            elif shown:
                extra = eyes.moments_sheet(movie, shown, work)
                made = [*made, extra] if extra else made
        return made

    answer = _answer(host, facts, sheets)
    if isinstance(answer, Reply) and text_dropped:
        answer.data["text_frames"] = ("not shown: this conversation has no room for one more picture. Say in the report "
                                      "that the text over the film was not looked at.")
    if isinstance(answer, Reply) and covered:
        more = covered[-1] + 1 < len(project.scenes)
        answer.data["pictures_cover_scenes"] = f"{covered[0]} to {covered[-1]} (of {len(project.scenes)})"
        if more:
            answer.data["more"] = f"scenes {covered[-1] + 1} on are not shown: call again with from_scene={covered[-1] + 1}"
        host.showed(0, covered)
    return answer


@tool("look_at_scene",
      "Look at one scene's clip (or one of its takes, from list_takes) before the film is exported: frames spread over the clip "
      "on one sheet. Use it after a clip is made, to see whether it shows what the scene should, then fix it with edit_scene or "
      "a new take (timeline_job prepare_scene) if it does not.",
      obj({"project_id": text("The project id.", max_length=32, pattern=_ID),
           "scene": whole("The scene number (0 is the first).", 0, 59),
           "frames": whole("How many frames (default 4).", 1, 8),
           "take": text("A take's key from list_takes (default: the take the film shows).", max_length=80)},
          ("project_id", "scene")))
def _look_at_scene(host: Host, args: dict):
    project = _load(args["project_id"])
    index = args["scene"]
    if not 0 <= index < len(project.scenes):
        raise ToolError("INVALID", "scene is not a scene of the project.")
    keys = list(timeline.prepared(project)["assets"])
    key = args.get("take") or (keys[index] if index < len(keys) else None)
    if not key:
        raise ToolError("INVALID", f"Scene {index + 1} has no clip yet (timeline_job prepare_scene or prepare_missing).")
    if args.get("take") and not any(take["key"] == key for take in timeline.takes(project, index)):
        raise ToolError("NOT_FOUND", "That take is not one of this scene's takes (list_takes).")
    record = timeline.asset(project, key, verify=False)
    if record is None:
        raise ToolError("NOT_FOUND", "That clip is missing or changed.")
    facts = {**_scene_facts(project, index), "take": key[:12], "clip_seconds": record.get("seconds"),
             "spoken": [{"who": row.get("character") or row.get("voice"), "text": row.get("text"),
                         "from": row.get("start"), "to": row.get("end")} for row in record.get("dialogue_timings") or []][:12],
             "studio_checks": _studio_checks(record.get("qc"))}
    if host.settings["send_images"] and eyes.film_shows_uploaded(project, [record]):
        return {**facts, "pictures": UPLOADED}
    clip, seconds = Path(record["path"]), float(record.get("seconds") or 5)
    return _answer(host, facts, lambda: [eyes.clip_sheet(clip, seconds, args.get("frames", 4), host.store.path("work"),
                                                         f"Scene {index + 1}")], scenes=[index])


def _studio_checks(quality) -> dict:
    """The clip's independent shot check as the agent reads it: its status (only "pass" is a pass: "unchecked" means
    nobody checked the clip), why it failed, and the full record."""
    from . import shot_qc

    verdict = shot_qc.QcVerdict.from_record(quality)
    return {"status": verdict.status, "passed": verdict.status == shot_qc.PASS,
            "failing": [f"[{check.defect or '?'}] {check.detail or check.name}" for check in verdict.checks
                        if check.status == shot_qc.FAIL][:10],
            "note": "Binding: a shot that did not pass cannot be delivered as complete." if verdict.status != shot_qc.PASS
            else "", "record": quality}


def _kind_module(kind: str):
    return characters if kind == "character" else items


@tool("look_at_photos",
      "Look at the photos of a character or a place (kind character or item): of a saved one by its slug, or of a draft "
      "this run made (before finish_character / finish_item), on one sheet. Check the person's age, face, clothes and the "
      "style against the brief; fix a wrong photo with fix_photo (photo 1 is the first on the sheet).",
      obj({"kind": choice("character or item.", "character", "item"),
           "slug": text("The slug of a saved character or place.", max_length=80),
           "draft_id": text("The id of a draft of this run.", max_length=64)}, ("kind",)))
def _look_at_photos(host: Host, args: dict):
    kind, slug, draft = args["kind"], args.get("slug"), args.get("draft_id")
    if bool(slug) == bool(draft):
        raise ToolError("INVALID", "Give exactly one of slug (a saved one) or draft_id (a draft of this run).")
    module = _kind_module(kind)
    if draft:
        if not host.is_mine(f"{kind}_draft", draft):
            raise ToolError("NOT_FOUND", f"This run has no {kind} draft with that id.")
        try:
            held = module.draft_photos(draft)
        except (ValueError, OSError):
            raise ToolError("NOT_FOUND", "That draft is gone.")
        paths = [path for path, _ in held]
        stays = not eyes.only_generated([entry for _, entry in held])
        facts = {"draft_id": draft, "photos": len(paths), "origins": [entry.get("origin", "") for _, entry in held]}
        title = "Draft"
    else:
        found = module.get(slug)
        if found is None:
            raise ToolError("NOT_FOUND", f"No such {kind}.")
        paths = [Path(path) for path in found.get("photos") or []]
        stays = eyes.photos_were_uploaded(kind, slug)
        facts = {"slug": slug, "name": found.get("name"), "look": found.get("look", ""), "photos": len(paths)}
        title = found.get("name") or slug
    if stays and host.settings["send_images"]:
        return {**facts, "pictures": UPLOADED}
    return _answer(host, facts, lambda: [eyes.photos_sheet(paths, str(title))])


@tool("fix_photo",
      "Correct a photo of a draft of this run (a character or a place before it is saved): regenerate it (queues a new photo "
      "in its place; wait_for_jobs, then look again) or remove it (the photos after it move up by one). Only a generated photo "
      f"can be regenerated, and only when no photo job of the draft is waiting. At most {TRIES_PER_PHOTO} tries for a photo; "
      "then accept it or say in finish_run that it is not right.",
      obj({"kind": choice("character or item.", "character", "item"),
           "draft_id": text("The draft id.", max_length=64),
           "photo": whole("The photo's number on the sheet (1 is the first).", 1, 8),
           "action": choice("regenerate or remove.", "regenerate", "remove")}, ("kind", "draft_id", "photo", "action")))
def _fix_photo(host: Host, args: dict):
    host.require("write", "Correcting a photo")
    kind, draft, index = args["kind"], args["draft_id"], args["photo"] - 1
    if not host.is_mine(f"{kind}_draft", draft):
        raise ToolError("NOT_FOUND", f"This run has no {kind} draft with that id.")
    module = _kind_module(kind)
    if module._draft_jobs(draft):  # a waiting job would put its photos where the numbers have moved
        raise ToolError("BUSY", "A photo job of this draft is still waiting or running. wait_for_jobs first.")
    if args["action"] == "remove":
        module.remove_photo(draft, index)
        return {"removed": args["photo"], "photos_left": len(module.draft_photos(draft))}
    host.spend_try(f"photo:{draft}:{index}", TRIES_PER_PHOTO, f"Photo {args['photo']}")
    with host.queue_scope():
        job = module.enqueue_regenerate(draft, index)
    return {"job_id": job.id, "next": "wait_for_jobs, then look_at_photos again"}
