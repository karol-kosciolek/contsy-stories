"""What the agent sees: pictures made from the studio's own results, small enough to send and laid out so that one look
answers a question (does every scene match the brief? is a character's photo right?). Frames of a film or a clip come
from ffmpeg, photos from the library; every sheet is a JPEG with a label on each cell. Nothing here sends anything: the
tools decide whether the pictures may leave this PC (app/agent_tools_eyes.py).

What may leave the PC is decided by provenance and fails closed: the pictures of a character or a place go only when the
record PROVES that every one of its photos was generated by Contsy. A photo the owner uploaded, a photo kept from an
earlier save (its origin is no longer known), a record that cannot be read: all of those stay on this PC."""
from __future__ import annotations

import io
import json
import uuid
from pathlib import Path
from typing import Optional, Sequence

from PIL import Image, ImageDraw, ImageFont

from . import characters, ffmpeg_utils, items, timeline

MAX_SIDE = 1568           # the longest side of a picture sent to the model
CELL = 480                # the width of a cell of a sheet
COLUMNS = 3
CELLS_PER_SHEET = 9
MAX_SHEETS = 3
JPEG_QUALITY = 84


def _font(size: int):
    try:
        return ImageFont.load_default(size=size)
    except (TypeError, OSError):
        return ImageFont.load_default()


def encode(image: Image.Image) -> bytes:
    image = image.convert("RGB")
    if max(image.size) > MAX_SIDE:
        image = image.copy()
        image.thumbnail((MAX_SIDE, MAX_SIDE))
    out = io.BytesIO()
    image.save(out, "JPEG", quality=JPEG_QUALITY)
    return out.getvalue()


def frame_image(video: Path, seconds: float, work: Path) -> Optional[Image.Image]:
    """One frame of a video, or None when it cannot be read."""
    target = work / f"eye_{uuid.uuid4().hex[:10]}.png"
    try:
        work.mkdir(parents=True, exist_ok=True)
        ok, _ = ffmpeg_utils.frame_at(video, max(seconds, 0.0), target)
        if not ok or not target.is_file():
            return None
        with Image.open(target) as opened:
            return opened.convert("RGB")
    except (OSError, ValueError):
        return None
    finally:
        try:
            target.unlink(missing_ok=True)
        except OSError:  # a scanner may hold the file for a moment: the frame is still good
            pass


def labelled(image: Image.Image, text: str, width: int = CELL) -> Image.Image:
    """The picture at `width` with a dark strip carrying `text` along its top edge."""
    image = image.convert("RGB")
    height = max(int(image.height * width / image.width), 1)
    image = image.resize((width, height))
    draw = ImageDraw.Draw(image)
    font = _font(max(width // 26, 12))
    box = draw.textbbox((0, 0), text, font=font)
    draw.rectangle((0, 0, min(box[2] + 14, width), box[3] + 10), fill=(0, 0, 0))
    draw.text((7, 3), text, fill=(255, 255, 255), font=font)
    return image


def sheet(cells: Sequence[tuple[str, Image.Image]], columns: int = COLUMNS, width: int = CELL) -> bytes:
    """A grid of labelled pictures as one JPEG."""
    shown = [labelled(image, text, width) for text, image in cells]
    columns = max(1, min(columns, len(shown)))
    rows = (len(shown) + columns - 1) // columns
    row_heights = [max(cell.height for cell in shown[row * columns:(row + 1) * columns]) for row in range(rows)]
    canvas = Image.new("RGB", (columns * width, sum(row_heights)), (20, 20, 20))
    top = 0
    for row in range(rows):
        for column, cell in enumerate(shown[row * columns:(row + 1) * columns]):
            canvas.paste(cell, (column * width, top))
        top += row_heights[row]
    return encode(canvas)


def _spread(step: int, count: int, seconds: float) -> float:
    """The moment of frame `step` of `count` in a shot of `seconds`: from just after the start to just before the end,
    so the last frame of a shot is always seen (a shot often goes wrong in its last second: a stranger walks in)."""
    if count <= 1:
        return seconds / 2
    first, last = min(0.1, seconds / 4), max(seconds - 0.12, seconds * 3 / 4)
    return first + (last - first) * step / (count - 1)


def single_frame(video: Path, seconds: float, work: Path) -> tuple[Optional[bytes], float]:
    """(a full-size frame labelled with its time, the time it shows): a time past the film's end shows its last frame."""
    length = ffmpeg_utils.probe_duration(video) or seconds
    moment = min(max(seconds, 0.0), max(length - 0.1, 0.0))
    image = frame_image(video, moment, work)
    if image is None:
        return None, moment
    return encode(labelled(image, f"{moment:.1f} s", min(image.width, MAX_SIDE))), moment


def film_cells(film: Path, scenes: Sequence, per_scene: int, work: Path, *, first: int = 0,
               limit: int = CELLS_PER_SHEET * MAX_SHEETS) -> list[tuple[int, str, Image.Image]]:
    """Frames of a finished film, `per_scene` for each scene from scene `first` (0 is the first) on, at most `limit` of
    them: (scene index, label, frame). The scenes' lengths are scaled to the film's own length (the export fades in and
    out), so a frame falls inside its scene. Labels count scenes from 1, as the owner reads them."""
    total = sum(scene.seconds for scene in scenes) or 1.0
    length = ffmpeg_utils.probe_duration(film) or total
    scale = length / total
    cells, start = [], 0.0
    for number, scene in enumerate(scenes):
        if number >= first:
            if len(cells) + per_scene > limit:
                break
            for step in range(per_scene):
                moment = (start + _spread(step, per_scene, scene.seconds)) * scale
                image = frame_image(film, min(moment, max(length - 0.1, 0.0)), work)
                if image is not None:
                    suffix = f" ({step + 1}/{per_scene})" if per_scene > 1 else ""
                    cells.append((number, f"Scene {number + 1}{suffix} · {moment:.1f} s", image))
        start += scene.seconds
    return cells


def film_sheets(film: Path, scenes: Sequence, per_scene: int, work: Path, *, first: int = 0,
                max_sheets: int = MAX_SHEETS) -> tuple[list[bytes], list[int]]:
    """(the sheets, the scene indexes they cover): CELLS_PER_SHEET frames to a sheet, at most `max_sheets` sheets. The scenes
    that did not fit are not shown: the caller says which ones and where to go on (`first`)."""
    cells = film_cells(film, scenes, per_scene, work, first=first, limit=CELLS_PER_SHEET * max_sheets)
    sheets = [sheet([(label, image) for _, label, image in cells[start:start + CELLS_PER_SHEET]])
              for start in range(0, len(cells), CELLS_PER_SHEET)]
    return sheets, sorted({number for number, _, _ in cells})


def moments_sheet(film: Path, moments: Sequence[tuple[str, float]], work: Path) -> Optional[bytes]:
    """One sheet of the frames of a film at the given (label, second) moments, at most CELLS_PER_SHEET of them (the text
    laid over a film is looked at this way: a frame in the middle of each overlay)."""
    length = ffmpeg_utils.probe_duration(film) or 0.0
    cells = []
    for label, seconds in list(moments)[:CELLS_PER_SHEET]:
        moment = min(max(seconds, 0.0), max(length - 0.1, 0.0))
        image = frame_image(film, moment, work)
        if image is not None:
            cells.append((f"{label} · {moment:.1f} s", image))
    return sheet(cells) if cells else None


def clip_sheet(clip: Path, seconds: float, frames: int, work: Path, title: str) -> Optional[bytes]:
    """`frames` frames spread over one clip."""
    cells = []
    for step in range(frames):
        moment = _spread(step, frames, seconds)
        image = frame_image(clip, moment, work)
        if image is not None:
            cells.append((f"{title} · {moment:.1f} s", image))
    return sheet(cells, columns=2 if frames <= 4 else 3) if cells else None


def photos_sheet(paths: Sequence[Path], title: str) -> Optional[bytes]:
    cells = []
    for number, path in enumerate(paths, 1):
        try:
            with Image.open(path) as opened:
                cells.append((f"{title} · photo {number}", opened.convert("RGB")))
        except (OSError, ValueError):
            continue
    return sheet(cells, columns=3, width=420) if cells else None


# --- what must stay on this PC ---------------------------------------------------------------------------------------

def only_generated(photos) -> bool:
    """True only when there are photos and EVERY one is recorded as generated by Contsy. 'uploaded', 'kept' (the origin of
    a photo after the character was opened for editing and saved again: its first origin is gone), a missing or unknown
    origin, no photos at all: not proven, so not true."""
    return isinstance(photos, list) and bool(photos) and all(
        isinstance(photo, dict) and photo.get("origin") == "generated" for photo in photos)


def photos_were_uploaded(kind: str, slug: str) -> bool:
    """Whether the pictures of a saved character or place must stay on this PC (see only_generated). A record that cannot be
    read counts as yes."""
    try:
        path = characters._file(slug) if kind == "character" else items._file(slug)
        record = json.loads(path.read_text(encoding="utf-8"))
        return not only_generated(record.get("photos"))
    except (OSError, ValueError, TypeError, AttributeError):
        return True


def film_shows_uploaded(project, records: Sequence[dict] = ()) -> bool:
    """Whether a film, or a clip of it, may show a character or a place whose pictures must stay on this PC. It looks at who
    is really in the scenes: the project's cast, each scene's own cast, who speaks, the characters and places the scene's text
    names, and the characters of the clip records shown. Anything that cannot be worked out counts as yes."""
    slugs, places = set(project.cast_slugs), set(project.items)
    try:
        for scene in project.scenes:
            slugs.update(scene.cast or ())
            slugs.update(cue.character for cue in scene.lines if cue.character)
            slugs.update(member["slug"] for member in timeline._scene_cast(project, scene))
            places.update(one["slug"] for one in timeline.named_items(scene))
        for record in records:
            slugs.update(record.get("characters") or ())
    except Exception:  # noqa: BLE001 - what cannot be worked out is not shown
        return True
    return (any(photos_were_uploaded("character", slug) for slug in slugs)
            or any(photos_were_uploaded("item", slug) for slug in places))
