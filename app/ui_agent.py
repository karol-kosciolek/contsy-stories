# --- forms and settings -------------------------------------------------------------------------------------------

def settings_from_form(*values) -> dict:
    """The settings the form's values make (checked): the values come in the order of SETTING_FIELDS, BUDGET_FIELDS,
    PERMISSION_FIELDS."""
    count = len(SETTING_FIELDS)
    base = dict(zip(SETTING_FIELDS, values[:count]))
    budgets = dict(zip(BUDGET_FIELDS, values[count:count + len(BUDGET_FIELDS)]))
    permissions = dict(zip(PERMISSION_FIELDS, values[count + len(BUDGET_FIELDS):]))
    return agent_config.clean_settings({**base, "budgets": budgets, "permissions": permissions})


def form_from_settings(settings: dict) -> tuple:
    return (*(settings[name] for name in SETTING_FIELDS), *(settings["budgets"][name] for name in BUDGET_FIELDS),
            *(settings["permissions"][name] for name in PERMISSION_FIELDS))


def model_hint_html(model) -> str:
    spec = provider.MODELS.get(model) or provider.MODELS[provider.DEFAULT_MODEL]
    price = (f"About ${spec.input:g} per million tokens in and ${spec.output:g} out "
             f"(an estimate from {provider.PRICES_AS_OF}).")
    return f"<p class='hint'>{esc(spec.hint)} {esc(price)}</p>"


# --- the key ------------------------------------------------------------------------------------------------------

def key_status_note(extra: str = "") -> str:
    status = agent_config.key_status()
    if status["source"] == "environment":
        saved = " A key saved here is not used while it is set." if status["saved"] else ""
        text = f"✅ Using the key of the ANTHROPIC_API_KEY variable ({esc(status['hint'])}).{saved}"
    elif status["source"] == "saved":
        text = f"✅ Key saved ({esc(status['hint'])}). It is encrypted for your Windows account."
    elif not status["encrypt"]:
        text = ("⚠ This PC cannot encrypt a key here. Set the ANTHROPIC_API_KEY environment variable and restart "
                "Contsy.")
    else:
        text = ("⚠ No key saved. Paste your Claude API key and click Save key. Everything else here works; only "
                "Start waits for a key.")
    return note(text + (f" {esc(extra)}" if extra else ""))


def save_key_click(text):
    problem = agent_config.save_key(text or "")
    if problem:
        return note(f"❌ {esc(problem)}"), gr.skip()
    return key_status_note("Not tested yet."), ""


def remove_key_click():
    agent_config.clear_key()
    return key_status_note("The saved key was removed."), ""


def test_connection_click(model, progress=gr.Progress()):
    """One free request that proves the key and the model (it asks for the model's name; nothing is sampled)."""
    status = agent_config.key_status()
    if status["source"] == "none":
        return note("❌ Save a key first.")
    spec = provider.MODELS.get(model) or provider.MODELS[provider.DEFAULT_MODEL]
    progress(0.2, desc="Asking Anthropic…")
    started = time.monotonic()
    try:
        name = provider.get_provider().ping(spec.id)
    except provider.ProviderError as error:
        return note(f"❌ {esc(error.user_message)}")
    except Exception as error:  # noqa: BLE001 - the page must answer
        return note(f"❌ The connection test failed: {esc(agent_config.redact(error))}")
    return note(f"✅ Connected. {esc(name)} answered in {time.monotonic() - started:.1f} s.")


# --- the brief ----------------------------------------------------------------------------------------------------

def _paths(value) -> list[str]:
    if not value:
        return []
    items = value if isinstance(value, (list, tuple)) else [value]
    return [str(getattr(item, "name", item)) for item in items if item]


def files_html(accepted, rejected) -> str:
    rows = [[esc(item.name), esc(item.kind), esc(agent_brief.describe_size(item.size)), esc(item.sha256[:10]),
             badge("Accepted", "ok") + (f"<br><span class='muted'>{esc(PDF_NOTE)}</span>" if item.kind == "pdf" else "")]
            for item in accepted]
    rows += [[esc(name), "", "", "", badge("Refused", "err") + f"<br><span class='muted'>{esc(reason)}</span>"]
             for name, reason in rejected]
    return table(["File", "Kind", "Size", "SHA-256", "Status"], rows,
                 empty="<b>No files yet</b>Attach the brief: .md, .txt, .docx, .json, .csv, a PDF, or pictures.")


def files_change(files, send_images):
    """The table of the attached files and how many were accepted."""
    accepted, rejected = agent_brief.inspect_many(_paths(files), bool(send_images))
    return files_html(accepted, rejected), len(accepted)


# --- Start --------------------------------------------------------------------------------------------------------

def start_state(*, key: dict, accepted: int, extra: str, mode: str, downloads: bool,
                running: bool = False, ready: bool = True) -> tuple[bool, str]:
    """(Start is possible, the one reason it is not or a note), the reasons in the order the owner can fix them."""
    if key.get("source") == "none":
        return False, "❌ Add your Claude key above to start."
    if not accepted and not (extra or "").strip():
        return False, "❌ Add a brief file or write instructions."
    problem = agent_brief.extra_problem(extra)
    if problem:
        return False, f"❌ {problem}"
    if running:
        return False, "⚠ A run is already in progress."
    missing = agent_preflight.blocking_models(mode, downloads)
    if missing:
        return False, f"❌ {missing}"
    if not ready:
        return False, "⚠ The run loop is not part of this build yet."
    if mode == "produce":
        return True, "✅ Ready. Producing uses the GPU: watch it in GPU Queue."
    return True, "✅ Ready. The agent will prepare everything and wait for your approval."


def preflight_html(mode, downloads) -> str:
    rows = [[esc(check.name), badge({"ok": "Ready", "warn": "Check", "err": "Problem", "info": "Note"}[check.state],
                                    check.state), esc(check.detail)]
            for check in agent_preflight.checks(mode, key=agent_config.key_status(),
                                                downloads_allowed=bool(downloads))]
    return table(["Check", "Status", "Details"], rows)


def _when(stamp) -> str:
    try:
        return time.strftime("%d %b %H:%M", time.localtime(float(stamp)))
    except (TypeError, ValueError, OverflowError, OSError):
        return ""


def history_html() -> str:
    rows = []
    for run in agent_store.list_runs()[:25]:
        label, kind = STATE_BADGE.get(run.get("state"), (str(run.get("state", "")), ""))
        brief = esc(run.get("title") or "") or ", ".join(esc(item.get("name", "")) for item in
                                                        (run.get("brief") or [])[:3]) or "—"
        usage = run.get("usage") or {}
        cost = f"${float(usage['cost_usd']):.2f}" if isinstance(usage.get("cost_usd"), (int, float)) else ""
        rows.append([esc(_when(run.get("created"))), brief, esc((run.get("settings") or {}).get("mode", "")),
                     badge(label, kind), esc(cost)])
    return table(["Started", "Brief", "Mode", "State", "Cost"], rows,
                 empty="<b>No runs yet</b>A run you start shows up here and stays after a restart.")


def refresh_status(accepted, extra, mode, downloads):
    """The panels read from the server: the key, the preflight, the history and Start with its reason."""
    mode = mode if mode in agent_config.MODES else "prepare"
    enabled, reason = start_state(key=agent_config.key_status(), accepted=int(accepted or 0), extra=extra or "",
                                  mode=mode, downloads=bool(downloads), running=agent_runner.busy(),
                                  ready=runner_available())
    return (key_status_note(), preflight_html(mode, downloads), history_html(), gr.update(interactive=enabled),
            note(reason))


def load_everything(accepted, extra):
    """The page loads: the saved settings fill the form, then the panels are read."""
    settings = agent_config.load_settings()
    values = form_from_settings(settings)
    status = refresh_status(accepted, extra, settings["mode"], settings["permissions"]["downloads"])
    return (*values, model_hint_html(settings["model"]), mode_about_html(settings["mode"]), *status)


def mode_about_html(mode) -> str:
    return f"<p class='hint'>{esc(MODE_ABOUT.get(mode, ''))}</p>"


def save_defaults(*values):
    saved = agent_config.save_settings(settings_from_form(*values))
    return note("✅ Saved as your defaults. The consent for attached files is never saved; it is asked for every run."
                if saved else "")


