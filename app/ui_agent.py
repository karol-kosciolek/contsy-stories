def build_agent_tab(tab: gr.Tab):
    page_head("Agent", "Give Contsy a brief and an AI agent plans and makes the whole job: the project, the characters "
                       "and places, the scenes, the sound, the finished movies and the documents for your client. "
                       "The agent thinks in the cloud (Claude, with your own key); everything is generated on this PC.")
    accepted = gr.State(0)  # how many of the attached files were accepted
    with gr.Column(elem_classes=["card"]):
        section("Connection", "Claude is the AI that runs the job. Your key stays on this PC, encrypted for your "
                              "Windows account, and is sent only to Anthropic.")
        with gr.Row():
            gr.Dropdown(provider.provider_choices(), value=provider.DEFAULT_PROVIDER, label="AI provider",
                        interactive=False, elem_id="agent-provider", scale=1)
            model = gr.Dropdown(provider.model_choices(), value=provider.DEFAULT_MODEL, label="Model",
                                interactive=True, elem_id="agent-model", scale=2)
        model_hint = gr.HTML(model_hint_html(provider.DEFAULT_MODEL), padding=False)
        key = gr.Textbox(label="Claude API key", type="password", placeholder="sk-ant-…", max_lines=1,
                         elem_id=KEY_FIELD, info="Create it in the Claude Console. The box is emptied once saved.")
        with gr.Row(elem_classes=["toolbar"]):
            save_key = gr.Button("Save key", size="sm", variant="primary", elem_id="agent-save-key")
            test = gr.Button("Test connection", size="sm", elem_id="agent-test")
            remove = gr.Button("Remove key", size="sm", variant="stop", elem_id="agent-remove-key")
        key_status = gr.Markdown(elem_classes=["status-box"], elem_id="agent-key-status")
        gr.HTML(PRIVACY, padding=False)
    with gr.Column(elem_classes=["card"]):
        section("Brief", "What the job is. Text, a Word file, a PDF, pictures of the client's brand: attach what you "
                         "have and add your own words below if you like.")
        files = gr.File(file_count="multiple", file_types=agent_brief.FILE_TYPES, label="Brief files",
                        elem_id="agent-files")
        files_table = gr.HTML(files_html([], []), padding=False, elem_id="agent-files-table")
        extra = gr.Textbox(label="Extra instructions (optional)", lines=3, max_lines=8, max_length=agent_brief.MAX_EXTRA,
                           placeholder="For example: two versions, 30 s and 15 s, friendly tone, no voice-over. This "
                                       "wins over the brief where they differ.", elem_id="agent-extra")
    with gr.Column(elem_classes=["card"]):
        section("Options")
        mode = gr.Radio(MODES, value="prepare", label="What the agent does", elem_id="agent-mode")
        mode_hint = gr.HTML(mode_about_html("prepare"), padding=False)
        with gr.Row():
            effort = gr.Dropdown(EFFORTS, value=provider.DEFAULT_EFFORT, label="Thoroughness",
                                 info="More thorough plans better and costs more.", elem_id="agent-effort", scale=1)
            send_images = gr.Checkbox(True, label="Send images to the cloud", elem_id="agent-send-images", scale=2,
                                      info="On (recommended): the agent looks at the characters, scenes and finished film "
                                           "it makes, checks them against the brief and corrects them, as an editor would. "
                                           "Off: it works blind and only text is sent. A PDF you attach as the brief is sent "
                                           "either way.")
            keep_awake = gr.Checkbox(True, label="Keep this PC awake while the agent works",
                                     elem_id="agent-keep-awake", scale=2)
        with gr.Row():
            budgets = [gr.Number(agent_config.DEFAULT_BUDGETS[name], label=BUDGET_LABELS[name], precision=2,
                                 minimum=agent_config.BUDGET_LIMITS[name][0],
                                 elem_id=f"agent-{name.replace('_', '-')}") for name in BUDGET_FIELDS]
        gr.HTML("<p class='hint'>The run stops and waits for your approval when it reaches the cost limit. Also set a spend "
                "limit in the Claude Console: this meter is an estimate.</p>", padding=False)
        section("Permissions", "What the agent may do beyond reading and creating. The agent has a tool for every "
                               "Contsy function; these decide which of them it may use.")
        permission_boxes = [gr.Checkbox(name == "write", label=PERMISSION_TEXT[name][0], info=PERMISSION_TEXT[name][1],
                                        elem_id=f"agent-permission-{name.replace('_', '-')}")
                            for name in PERMISSION_FIELDS]
        with gr.Row(elem_classes=["toolbar"]):
            defaults = gr.Button("Save as my defaults", size="sm", elem_id="agent-save-defaults")
            defaults_status = gr.Markdown(elem_classes=["status-box", "grow"])
    form = [model, effort, mode, send_images, keep_awake, *budgets, *permission_boxes]
    downloads = permission_boxes[PERMISSION_FIELDS.index("downloads")]
    with gr.Column(elem_classes=["card"]):
        section("Before you start")
        preflight = gr.HTML("", padding=False, elem_id="agent-preflight")
        with gr.Row(elem_classes=["toolbar"]):
            start = gr.Button("Start", variant="primary", size="sm", interactive=False, elem_id="agent-start")
            start_note = gr.Markdown(elem_classes=["status-box", "grow"], elem_id="agent-start-note")
    with gr.Column(elem_classes=["card"]):
        section("Run", "Watch the agent work. A run goes on when you close this page.")
        run_pick = gr.Dropdown([], value=None, label="Run", interactive=True, elem_id="agent-run-pick",
                               allow_custom_value=False)
        run_view = gr.HTML(ui_agent_run.run_html({}), padding=False, elem_id="agent-run")
        deliver = gr.File(label="Downloads", file_count="multiple", interactive=False, visible=False,
                          elem_id="agent-downloads")
        with gr.Row(elem_classes=["toolbar"]):
            pause_btn = gr.Button("Pause", size="sm", interactive=False, elem_id="agent-pause")
            stop_btn = gr.Button("Stop", size="sm", variant="stop", interactive=False, elem_id="agent-stop")
            resume_btn = gr.Button("Resume", size="sm", interactive=False, elem_id="agent-resume")
            approve_btn = gr.Button("Approve and produce", size="sm", variant="primary", interactive=False,
                                    elem_id="agent-approve")
        run_note = gr.Markdown(elem_classes=["status-box"], elem_id="agent-run-note")
    with gr.Column(elem_classes=["card"]):
        section("Runs")
        history = gr.HTML(history_html_empty(), padding=False, elem_id="agent-history")

    panels = [key_status, preflight, history, start, start_note]
    watched = [accepted, extra, mode, downloads]
    quiet = {"queue": False, "api_visibility": "private", "show_progress": "hidden"}
    ticker = gr.Timer(2.0, active=False)  # ticks only while a run works
    signature = gr.State("")
    live = [run_view, pause_btn, stop_btn, resume_btn, approve_btn, deliver, ticker, signature]

    def start_handler(files_value, extra_value, *values):
        message, run_id = ui_agent_run.start_click(_paths(files_value), extra_value or "", settings_from_form(*values))
        return message, (gr.update(choices=ui_agent_run.run_choices(), value=run_id) if isinstance(run_id, str)
                         else gr.skip())

    def forced(run_id):
        return ui_agent_run.show(run_id, force=True)

    def tick(run_id, last, *watched_values):
        """The run card (when something changed) and, with it, the panels that depend on the run: Start and the history."""
        shown = ui_agent_run.show(run_id, signature=last)
        if not isinstance(shown[-1], str):  # the signature is a string only when the run changed
            return (*shown, *(gr.skip(),) * len(panels))
        return (*shown, *refresh_status(*watched_values))

    def resume_handler(run_id, *values):
        """Resume a run. One that stopped at a limit goes on with the limits as they stand in the form; any other keeps the
        limits it was started with."""
        stopped = agent_store.valid_id(run_id) and agent_store.RunStore(run_id).read().get("state") == "budget_stopped"
        budgets = agent_config.clean_budgets(dict(zip(BUDGET_FIELDS, values))) if stopped else None
        return ui_agent_run.resume_click(run_id, budgets)

    def pick_runs(current):
        """The choices of the run list, with the working run (or the one shown, or the newest) selected."""
        choices = ui_agent_run.run_choices()
        ids = [value for _, value in choices]
        value = agent_runner.active() or (current if current in ids else (ids[0] if ids else None))
        return gr.update(choices=choices, value=value)

    start.click(start_handler, inputs=[files, extra, *form], outputs=[start_note, run_pick], api_visibility="private",
                queue=False).then(forced, inputs=run_pick, outputs=live, **quiet).then(
        refresh_status, inputs=watched, outputs=panels, **quiet)
    pause_btn.click(ui_agent_run.pause_click, inputs=run_pick, outputs=run_note, **quiet).then(
        forced, inputs=run_pick, outputs=live, **quiet)
    stop_btn.click(ui_agent_run.stop_click, inputs=run_pick, outputs=run_note, **quiet).then(
        forced, inputs=run_pick, outputs=live, **quiet)
    resume_btn.click(resume_handler, inputs=[run_pick, *budgets], outputs=run_note, **quiet).then(
        forced, inputs=run_pick, outputs=live, **quiet).then(refresh_status, inputs=watched, outputs=panels, **quiet)
    approve_btn.click(ui_agent_run.approve_click, inputs=run_pick, outputs=run_note, **quiet).then(
        forced, inputs=run_pick, outputs=live, **quiet).then(refresh_status, inputs=watched, outputs=panels, **quiet)
    run_pick.input(forced, inputs=run_pick, outputs=live, **quiet)
    ticker.tick(tick, inputs=[run_pick, signature, *watched], outputs=[*live, *panels], **quiet)
    save_key.click(save_key_click, inputs=key, outputs=[key_status, key], api_visibility="private").then(
        refresh_status, inputs=watched, outputs=panels, **quiet)
    remove.click(remove_key_click, outputs=[key_status, key], api_visibility="private").then(
        refresh_status, inputs=watched, outputs=panels, **quiet)
    test.click(test_connection_click, inputs=model, outputs=key_status, api_visibility="private")
    model.input(model_hint_html, inputs=model, outputs=model_hint, **quiet)
    files.change(files_change, inputs=[files, send_images], outputs=[files_table, accepted], **quiet).then(
        refresh_status, inputs=watched, outputs=panels, **quiet)
    send_images.input(files_change, inputs=[files, send_images], outputs=[files_table, accepted], **quiet).then(
        refresh_status, inputs=watched, outputs=panels, **quiet)
    mode.input(lambda value: mode_about_html(value), inputs=mode, outputs=mode_hint, **quiet).then(
        refresh_status, inputs=watched, outputs=panels, **quiet)
    for component in (extra, downloads):
        component.change(refresh_status, inputs=watched, outputs=panels, **quiet)
    defaults.click(save_defaults, inputs=form, outputs=defaults_status, api_visibility="private")
    # the saved settings fill the form once, when the page loads; a visit to the page only reads the panels again
    tab.select(refresh_status, inputs=watched, outputs=panels, **quiet).then(
        pick_runs, inputs=run_pick, outputs=run_pick, **quiet).then(forced, inputs=run_pick, outputs=live, **quiet)

    def wire(demo) -> None:
        """The page's load events, attached to the app's Blocks: the saved settings fill the form once when the page opens
        (a plain gr.on(None, ...) would fill it again at every change of a field), then the runs are listed and the
        chosen one is shown."""
        demo.load(load_everything, inputs=[accepted, extra], outputs=[*form, model_hint, mode_hint, *panels],
                  **quiet).then(pick_runs, inputs=run_pick, outputs=run_pick, **quiet).then(
            forced, inputs=run_pick, outputs=live, **quiet)

    return wire


def history_html_empty() -> str:
    """The history before the page loads (nothing is read from the disk while the page is built)."""
    return table(["Started", "Brief", "Mode", "State", "Cost"], [], empty="<b>No runs yet</b>")
